-- GradeBot schema (PostgreSQL 14+).

CREATE TABLE questions (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    text      TEXT NOT NULL CHECK (length(trim(text)) > 0),
    rubric    TEXT NOT NULL CHECK (length(trim(rubric)) > 0),
    max_marks NUMERIC(5,2) NOT NULL CHECK (max_marks > 0)
);

CREATE TABLE submissions (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id  BIGINT NOT NULL REFERENCES questions (id),
    student_id   TEXT NOT NULL CHECK (length(trim(student_id)) > 0),
    -- Empty answers are legitimate submissions (a student handed in a blank), so no length CHECK.
    answer       TEXT NOT NULL,
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- One row per grading run (not per LLM call): failed runs are kept for audit.
CREATE TABLE grades (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id  BIGINT NOT NULL REFERENCES submissions (id),
    score          NUMERIC(5,2),
    feedback       TEXT,
    status         TEXT NOT NULL CHECK (status IN ('success', 'failed')),
    model          TEXT NOT NULL,
    prompt_version TEXT NOT NULL,
    -- 0 = short-circuited by a rule without calling the LLM.
    attempts       INTEGER NOT NULL CHECK (attempts BETWEEN 0 AND 3),
    latency_ms     INTEGER NOT NULL CHECK (latency_ms >= 0),
    raw_response   JSONB,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),

    -- A failed run never carries a score; a successful one always has score + feedback.
    CONSTRAINT grades_score_matches_status CHECK (
        (status = 'success' AND score IS NOT NULL AND score >= 0 AND feedback IS NOT NULL)
        OR (status = 'failed' AND score IS NULL)
    )
);

-- Idempotency: at most one successful grade per (submission, prompt version).
-- Partial, so any number of failed runs can coexist with it.
CREATE UNIQUE INDEX uq_grades_one_success
    ON grades (submission_id, prompt_version)
    WHERE status = 'success';

-- "Latest grade per submission" (queries.sql c) and per-submission history read this in order.
CREATE INDEX idx_grades_submission_created
    ON grades (submission_id, created_at DESC, id DESC);

-- GET /grades?question_id= and the per-question report join submissions by question;
-- Postgres does not index FK columns automatically.
CREATE INDEX idx_submissions_question_id
    ON submissions (question_id);

-- score <= max_marks spans two tables, so a CHECK cannot express it. The app validates this
-- before inserting; the trigger is the backstop for any other writer.
CREATE FUNCTION grades_score_within_max_marks() RETURNS trigger AS $$
DECLARE
    q_max NUMERIC(5,2);
BEGIN
    IF NEW.score IS NOT NULL THEN
        SELECT q.max_marks INTO q_max
        FROM submissions s
        JOIN questions q ON q.id = s.question_id
        WHERE s.id = NEW.submission_id;

        IF NEW.score > q_max THEN
            RAISE EXCEPTION 'score % exceeds max_marks % for submission %',
                NEW.score, q_max, NEW.submission_id
                USING ERRCODE = 'check_violation';
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_grades_score_within_max_marks
    BEFORE INSERT OR UPDATE OF score ON grades
    FOR EACH ROW EXECUTE FUNCTION grades_score_within_max_marks();
